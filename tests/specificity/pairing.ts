/**
 * 合盤量測用的配對規則。量測腳本與具體性量測共用同一份，兩邊談的才是同一批配對。
 *
 * 為什麼不是「第 i 組配第 i+固定位移 組」：合成命盤的出生年份是照索引遞增的
 * （1920 + floor(i/500 × 100)），所以固定位移等於固定的年份差。第一版用位移 251，
 * 年份差固定是 50 年，而 50 mod 12 = 2——兩個人的年支永遠只差兩格，六沖（差六格）
 * 在 500 組配對裡一次都沒出現，量出來的 0% 是配對方式造成的，不是事實。
 *
 * 改成乘法跳躍後年份差隨索引變化，年支差才會鋪滿十二種。
 * 137 與 500 互質，因此 i ↦ partnerIndex(i) 是一個排列，每個人剛好被配到一次；
 * 又因 136i ≡ -71 (mod 500) 無解（gcd(136,500)=4 不整除 429），不會有人配到自己。
 */
export function partnerIndex(index: number, count: number): number {
  return (index * 137 + 71) % count;
}
